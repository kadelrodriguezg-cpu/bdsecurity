import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import '@testing-library/jest-dom/vitest';
import { afterEach, expect, it, vi } from 'vitest';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { MemoryRouter, Route, Routes } from 'react-router';
import { qk } from '@/lib/queryKeys';
import { FichaEveclEditarPage } from './FichaEveclEditarPage';
const mocks = vi.hoisted(() => ({ ficha: vi.fn(), catalogo: vi.fn() }));
vi.mock('@/api/evecl', () => ({ obtenerFichaEvecl: mocks.ficha, obtenerCatalogoEvecl: mocks.catalogo }));
vi.mock('@/features/auth/AuthContext', () => ({ useAuth: () => ({ user:{id:'A'}, generacionSesion:1 }) }));
vi.mock('@/features/evecl/FichaForm', () => ({ FichaForm: () => <input aria-label="Edición en curso" defaultValue=""/> }));
afterEach(cleanup);
it('fallo de refetch conserva Sheet y formulario y reintenta solo ficha fallida', async () => {
  const datos = { variedad:'Variedad', ensayo:{codigo_parcela:'P'}, ensayo_id:1 };
  mocks.ficha.mockResolvedValue(datos);
  mocks.catalogo.mockResolvedValue([]);
  const qc = new QueryClient({defaultOptions:{queries:{retry:false}}});
  render(<QueryClientProvider client={qc}><MemoryRouter initialEntries={['/editar/1']}><Routes><Route path="/editar/:id" element={<FichaEveclEditarPage/>}/></Routes></MemoryRouter></QueryClientProvider>);
  const input = await screen.findByLabelText('Edición en curso');
  const sheet = screen.getByRole('dialog');
  fireEvent.change(input,{target:{value:'Pendiente'}});
  mocks.ficha.mockRejectedValue(new Error('private SQL'));
  await act(async () => { await qc.invalidateQueries({queryKey:qk.evecl.ficha(1)}); });
  const retry = await screen.findByRole('button',{name:'Reintentar ficha'});
  expect(screen.queryByText(/private SQL/)).not.toBeInTheDocument();
  expect(screen.getByRole('dialog')).toBe(sheet);
  expect(screen.getByLabelText('Edición en curso')).toBe(input);
  expect(input).toHaveValue('Pendiente');
  const catalogCalls=mocks.catalogo.mock.calls.length;
  mocks.ficha.mockResolvedValue(datos);
  fireEvent.click(retry);
  await waitFor(()=>expect(screen.queryByRole('button',{name:'Reintentar ficha'})).not.toBeInTheDocument());
  expect(mocks.catalogo).toHaveBeenCalledTimes(catalogCalls);
  expect(input).toHaveValue('Pendiente');
});
